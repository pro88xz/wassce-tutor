#!/usr/bin/env python3
"""Check a question set and generate its SQL and review sheet.

    pip install -r scripts/questions/requirements.txt
    python3 scripts/questions/build.py            # check + write files
    python3 scripts/questions/build.py --check    # check only

Every answer is recomputed by code (see qbank.py). If any question fails, no
files are written.

Output
  supabase/content/<set>.sql   paste into the Supabase SQL editor. Adds one
                               practice set (paper) per topic, hidden from
                               students (is_published = false) until a
                               reviewer approves it. Safe to run again: rows
                               have fixed ids, and a question whose text
                               changed loses its review.
  content/questions/<subject>/<set>.review.md
                               the questions as students will see them, with
                               the answer, the working and the reason behind
                               every wrong option, for the reviewer.
"""

from __future__ import annotations

import importlib.util
import sys
import uuid
from collections import Counter, OrderedDict
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

from qbank import CheckError, Q, check, is_number, num  # noqa: E402

SETS = [
    {
        "module": ROOT / "content/questions/mathematics/pilot_p1.py",
        "subject_slug": "mathematics",
        "name": "maths_pilot_p1",
        "sql": ROOT / "supabase/content/20261105_maths_pilot_questions.sql",
        "review": ROOT / "content/questions/mathematics/pilot_p1.review.md",
        "sort_from": 100,
    },
]

LABELS = "ABCD"
NS = uuid.UUID("6f1c3f5e-9a51-4d0e-b7a4-2f0c5d6e7a81")  # fixed namespace for stable ids


def uid(*parts: str) -> str:
    return str(uuid.uuid5(NS, "/".join(parts)))


def load(path: Path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def order_options(questions: list[Q]) -> dict[str, list[tuple[str, bool, int]]]:
    """Numbers go in ascending order (as on WAEC papers). Other options are
    placed so the correct answers end up spread evenly across A-D."""
    out: dict[str, list[tuple[str, bool, int]]] = {}
    used = Counter()
    later = []
    for q in questions:
        opts = [(q.answer[0], True, 0, q.answer[1])] + [(w.tex, False, i + 1, w.value) for i, w in enumerate(q.wrong)]
        if all(is_number(v) for *_, v in opts):
            opts.sort(key=lambda o: num(o[3]))
            out[q.id] = [(t, c, src) for t, c, src, _ in opts]
            used[[c for _, c, _, _ in opts].index(True)] += 1
        else:
            later.append((q, opts))
    for q, opts in later:
        slot = min(range(4), key=lambda k: (used[k], k))
        wrong = [o for o in opts if not o[1]]
        placed = wrong[:slot] + [opts[0]] + wrong[slot:]
        out[q.id] = [(t, c, src) for t, c, src, _ in placed]
        used[slot] += 1
    return out


def big_fracs(tex: str) -> str:
    """Write fractions full size (\\dfrac) so they are readable on a phone,
    except inside powers and subscripts, e.g. the 2/3 in 27^{\\frac{2}{3}}."""
    out, depth, scripts, i = [], 0, [], 0
    while i < len(tex):
        if tex.startswith("\\frac", i) and not scripts:
            out.append("\\dfrac")
            i += len("\\frac")
            continue
        ch = tex[i]
        if ch in "^_" and tex.startswith("{", i + 1):
            scripts.append(depth + 1)
        elif ch == "{":
            depth += 1
        elif ch == "}":
            if scripts and scripts[-1] == depth:
                scripts.pop()
            depth -= 1
        out.append(ch)
        i += 1
    return "".join(out)


def explanation(q: Q) -> str:
    # The app already shows the correct letter above this text.
    lines = [q.working.strip(), "", "**Why the other options are wrong**", ""]
    lines += [f"- {w.tex}: {w.why}" for w in q.wrong]
    return big_fracs("\n".join(lines))


def sql_str(s: str | None) -> str:
    return "null" if s is None else "'" + s.replace("'", "''") + "'"


def build_sql(cfg: dict, questions: list[Q], ordered: dict) -> str:
    topics = list(OrderedDict.fromkeys(q.topic for q in questions))
    by_topic = {t: [q for q in questions if q.topic == t] for t in topics}
    subj = sql_str(cfg["subject_slug"])
    out = [
        f"-- Generated by scripts/questions/build.py from {cfg['module'].relative_to(ROOT)}.",
        "-- Do not edit by hand: change the source file and run the build again.",
        "--",
        f"-- Adds {len(topics)} practice sets ({len(questions)} original questions) to {cfg['subject_slug']}.",
        "-- They stay hidden from students (papers.is_published = false) until a",
        "-- reviewer approves them in Admin -> Review lessons and questions.",
        "--",
        "-- Safe to run more than once. Rows have fixed ids. If a question or any of",
        "-- its options has changed since the last run, its review is cleared and",
        "-- its set is hidden again until a reviewer approves it.",
        "",
        "begin;",
        "",
        "do $$",
        "declare",
        "  missing text;",
        "begin",
        "  select string_agg(v.name, ', ') into missing",
        "  from (values " + ", ".join(f"({sql_str(t)})" for t in topics) + ") as v(name)",
        "  where not exists (",
        "    select 1 from public.topics t join public.subjects s on s.id = t.subject_id",
        f"    where s.slug = {subj} and t.name = v.name);",
        "  if missing is not null then",
        f"    raise exception 'Topics not found in {cfg['subject_slug']}: %', missing;",
        "  end if;",
        "end $$;",
        "",
    ]
    for i, topic in enumerate(topics):
        qs = by_topic[topic]
        pid = uid(cfg["name"], "paper", topic)
        title = f"{topic}: practice set 1"
        desc = (
            f"{len(qs)} original WASSCE-style objective questions on {topic.lower()}, each with a worked "
            "solution and the reason behind every wrong option. Written by WASSCE Tutor, not taken from WAEC papers."
        )
        topic_id = (
            "(select t.id from public.topics t join public.subjects s on s.id = t.subject_id "
            f"where s.slug = {subj} and t.name = {sql_str(topic)})"
        )
        out += [
            f"-- {topic}",
            "insert into public.papers (id, subject_id, title, paper_type, description, question_count, sort_order, is_published)",
            f"values ({sql_str(pid)}, (select id from public.subjects where slug = {subj}), {sql_str(title)}, 'Practice',",
            f"        {sql_str(desc)}, {len(qs)}, {cfg['sort_from'] + i}, false)",
            "on conflict (id) do update set title = excluded.title, paper_type = excluded.paper_type,",
            "  description = excluded.description, question_count = excluded.question_count, sort_order = excluded.sort_order;",
            "",
        ]
        for pos, q in enumerate(qs, start=1):
            qid = uid(cfg["name"], "question", q.id)
            out += [
                "insert into public.questions (id, paper_id, topic_id, stem, explanation, position)",
                f"values ({sql_str(qid)}, {sql_str(pid)}, {topic_id},",
                f"        {sql_str(big_fracs(q.stem))},",
                f"        {sql_str(explanation(q))},",
                f"        {pos})",
                "on conflict (id) do update set",
                "  paper_id = excluded.paper_id, topic_id = excluded.topic_id, stem = excluded.stem,",
                "  explanation = excluded.explanation, position = excluded.position,",
                "  is_public = case when (questions.stem, questions.explanation) is distinct from (excluded.stem, excluded.explanation) then false else questions.is_public end,",
                "  reviewed_at = case when (questions.stem, questions.explanation) is distinct from (excluded.stem, excluded.explanation) then null else questions.reviewed_at end,",
                "  reviewed_by = case when (questions.stem, questions.explanation) is distinct from (excluded.stem, excluded.explanation) then null else questions.reviewed_by end;",
                "with new_options (id, question_id, label, content, is_correct, position) as (values",
            ]
            rows = [
                f"  ({sql_str(uid(cfg['name'], 'option', q.id, str(src)))}::uuid, {sql_str(qid)}::uuid, '{LABELS[k]}', "
                f"{sql_str(big_fracs(text))}, {'true' if correct else 'false'}, {k})"
                for k, (text, correct, src) in enumerate(ordered[q.id])
            ]
            out.append(",\n".join(rows) + "),")
            out += [
                "changed as (  -- any option new or different: the question needs reviewing again",
                "  select distinct n.question_id from new_options n left join public.options o on o.id = n.id",
                "  where o.id is null or (o.label, o.content, o.is_correct, o.position) is distinct from (n.label, n.content, n.is_correct, n.position)),",
                "cleared as (",
                "  update public.questions q set is_public = false, reviewed_at = null, reviewed_by = null",
                "  from changed c where q.id = c.question_id returning q.id)",
                "insert into public.options (id, question_id, label, content, is_correct, position)",
                "select id, question_id, label, content, is_correct, position from new_options",
                "on conflict (id) do update set label = excluded.label, content = excluded.content,",
                "  is_correct = excluded.is_correct, position = excluded.position;",
                "",
            ]
    paper_ids = ", ".join(sql_str(uid(cfg["name"], "paper", t)) for t in topics)
    out += [
        "-- A live set that now contains an unreviewed question goes back to hidden",
        "-- until it is approved again, so students never see unchecked questions.",
        "update public.papers p set is_published = false",
        f"where p.id in ({paper_ids})",
        "  and p.is_published",
        "  and exists (select 1 from public.questions q where q.paper_id = p.id and q.reviewed_at is null);",
        "",
        "commit;",
        "",
    ]
    return "\n".join(out)


def build_review(cfg: dict, questions: list[Q], ordered: dict, scope_note: str) -> str:
    out = [
        f"# Review sheet: {cfg['name'].replace('_', ' ')}",
        "",
        f"Generated by `scripts/questions/build.py` from `{cfg['module'].relative_to(ROOT)}`. Do not edit by hand.",
        "",
        scope_note,
        "",
        "For each question, check: is it on the syllabus for Sierra Leone candidates, is it worded the way WAEC",
        "words questions, is the marked answer right, is every wrong option wrong, and is the working clear?",
        "Every answer below has also been recomputed by code before this sheet was made.",
        "",
    ]
    topic = None
    for num_, q in enumerate(questions, start=1):
        if q.topic != topic:
            topic = q.topic
            out += [f"## {topic}", "", f"_Syllabus: {q.ref}_", ""]
        out += [f"### {num_}. `{q.id}`", "", q.stem, ""]
        for k, (text, correct, _) in enumerate(ordered[q.id]):
            out.append(f"- **{LABELS[k]}.** {text}" + ("  ✅" if correct else ""))
        out += ["", explanation(q), "", "Reviewer: ☐ approved ☐ needs changes — notes:", "", "---", ""]
    return "\n".join(out)


def main() -> int:
    check_only = "--check" in sys.argv
    failures = 0
    for cfg in SETS:
        mod = load(cfg["module"])
        questions: list[Q] = mod.QUESTIONS
        ids = Counter(q.id for q in questions)
        dupes = [k for k, v in ids.items() if v > 1]
        if dupes:
            print(f"duplicate ids: {dupes}")
            failures += 1
        for q in questions:
            if q.topic not in mod.TOPICS:
                print(f"{q.id}: topic {q.topic!r} is not in TOPICS")
                failures += 1
            try:
                check(q)
            except CheckError as e:
                print(e)
                failures += 1
        if failures:
            continue
        ordered = order_options(questions)
        spread = Counter(LABELS[[c for _, c, _ in ordered[q.id]].index(True)] for q in questions)
        print(f"{cfg['name']}: {len(questions)} questions checked. Correct answers by letter: "
              + ", ".join(f"{k} {spread[k]}" for k in LABELS))
        if check_only:
            continue
        cfg["sql"].parent.mkdir(parents=True, exist_ok=True)
        cfg["sql"].write_text(build_sql(cfg, questions, ordered))
        scope = (mod.__doc__ or "").strip().splitlines()[0]
        cfg["review"].write_text(build_review(cfg, questions, ordered, scope))
        print(f"  wrote {cfg['sql'].relative_to(ROOT)} and {cfg['review'].relative_to(ROOT)}")
    if failures:
        print(f"\n{failures} problem(s). Nothing written.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
