def oral(id: str, topic: str, stem: str, answer: str, wrong: list[tuple[str, str]], working: str,
         order: list[str] | None = None) -> Q:
    """A four-option item. `wrong` is (option, why it is wrong)."""
    return Q(
        id=id, topic=topic, ref=TOPICS[topic], stem=stem,
        answer=(answer, answer),
        wrong=[Wrong(text, text, why) for text, why in wrong],
        solve=lambda a=answer: a,  # checked by an editor, not by code
        working=working,
        order=order,
    )


