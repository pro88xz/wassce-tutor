from qbank import Q, Wrong

TOPICS = {
    "Nouns": "Structure: nouns (countable and uncountable nouns, irregular plurals, possessive forms)",
    "Pronouns": "Structure: pronouns (case, relative, reflexive and possessive pronouns)",
    "Verbs and Verb Forms": "Structure: verbs (irregular forms, transitive and intransitive pairs, phrasal verbs, verb patterns)",
    "Tenses": "Structure: tense and aspect (present perfect, past perfect, continuous forms, time clauses)",
    "Active and Passive Voice": "Structure: the passive (form, tense, modals)",
    "Non-finite Verb Forms": "Structure: gerunds, infinitives and participles",
    "Adjectives": "Structure: adjectives (comparison, order, -ed and -ing forms, quantifiers)",
    "Prepositions": "Structure: prepositions (time, duration, fixed verb and adjective + preposition pairs)",
    "Conjunctions": "Structure: conjunctions (contrast, condition, purpose, correlative pairs)",
    "Subject-Verb Agreement": "Structure: concord (subject-verb agreement)",
}

COMPLETE = "Choose the option that best completes the sentence."


def mc(id: str, topic: str, sentence: str, answer: str, wrong: list[tuple[str, str]], working: str, stem: str | None = None) -> Q:
    """A four-option item. `wrong` is (option, the mistake it represents)."""
    return Q(
        id=id,
        topic=topic,
        ref=TOPICS[topic],
        stem=stem or f"{COMPLETE}\n\n{sentence}",
        answer=(answer, answer),
        wrong=[Wrong(text, text, why) for text, why in wrong],
        solve=lambda a=answer: a,  # checked by an editor, not by code
        working=working,
    )


