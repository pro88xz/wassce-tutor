from qbank import Q, Wrong

TOPICS = {
    "Parts of Speech": "Structure: identifying word classes by their job in the sentence",
    "Adverbs": "Structure: adverbs (form, position, comparison, hard/hardly, so... that)",
    "Articles": "Structure: a, an, the and no article",
    "Question Tags": "Structure: question tags (auxiliary, polarity, special cases)",
    "Modal Verbs": "Structure: modal verbs (obligation, permission, ability, deduction)",
    "Conditionals": "Structure: conditional sentences (first, second, third; unless; inversion)",
    "Direct and Reported Speech": "Structure: reported statements, questions and commands",
    "Synonyms and Antonyms": "Lexis: words nearest and opposite in meaning",
    "Idioms and Idiomatic Expressions": "Lexis: interpreting common idioms",
    "Common Confusable Words": "Lexis: words often confused (affect/effect, than/then, lose/loose)",
}

COMPLETE = "Choose the option that best completes the sentence."
POS = "What part of speech is the word in bold?"
NEAREST = "Choose the option nearest in meaning to the word in bold."
OPPOSITE = "Choose the option most nearly opposite in meaning to the word in bold."
IDIOM = "Choose the option that best explains the expression in bold."
REPORTED = "Choose the option that best reports this sentence."


def mc(id: str, topic: str, sentence: str, answer: str, wrong: list[tuple[str, str]], working: str, lead: str = COMPLETE) -> Q:
    """A four-option item. `wrong` is (option, the mistake it represents)."""
    return Q(
        id=id,
        topic=topic,
        ref=TOPICS[topic],
        stem=f"{lead}\n\n{sentence}".strip(),
        answer=(answer, answer),
        wrong=[Wrong(text, text, why) for text, why in wrong],
        solve=lambda a=answer: a,  # checked by an editor, not by code
        working=working,
    )


